// Writes plugin/engine/ParamsGen.h from src/engine/params.js and kits.js, so the JUCE plugin
// uses exactly the same parameter layout, ranges and starting kit as the browser version.
//   node tools/gen-cpp-params.mjs
import { writeFileSync } from 'node:fs';
import { PARAMS, MPARAMS, NP, MP, NUM_VOICES, VOICE_NAMES, ECHO_DIVS, RUSH_EVERY, SPEEDS } from '../src/engine/params.js';
import { kitToArray, INIT_KIT } from '../src/engine/kits.js';

const curve = { lin: 0, exp: 1, int: 2, bip: 3 };
const f = (x) => { const s = String(+x.toPrecision(9)); return /[.e]/.test(s) ? s + 'f' : s + '.0f'; };
const spec = (ps) => ps.map((p) => `  { "${p.id}", ${f(p.min)}, ${f(p.max)}, ${f(p.def)}, ${curve[p.curve]}, "${p.label}" },`).join('\n');
const kit = kitToArray(INIT_KIT);

const out = `// Generated by tools/gen-cpp-params.mjs from src/engine/params.js and kits.js. Do not edit.
#pragma once

namespace fmdm {

constexpr int NUM_VOICES = ${NUM_VOICES};
constexpr int NP = ${NP};
constexpr int MP = ${MP};
constexpr int NV = NUM_VOICES * NP;

enum Curve { CURVE_LIN = 0, CURVE_EXP = 1, CURVE_INT = 2, CURVE_BIP = 3 };
struct ParamSpec { const char* id; float min, max, def; int curve; const char* label; };

namespace P { enum : int { ${PARAMS.map((p) => p.id).join(', ')} }; }
namespace M { enum : int { ${MPARAMS.map((p) => p.id).join(', ')} }; }

inline const ParamSpec VOICE_SPEC[NP] = {
${spec(PARAMS)}
};
inline const ParamSpec MASTER_SPEC[MP] = {
${spec(MPARAMS)}
};

inline const char* const VOICE_NAMES[NUM_VOICES] = { ${VOICE_NAMES.map((n) => `"${n}"`).join(', ')} };
inline const float ECHO_DIV_BEATS[] = { ${ECHO_DIVS.map((d) => f(d[1])).join(', ')} };
inline const int RUSH_EVERY[] = { ${RUSH_EVERY.join(', ')} };
inline const int SPEED_STEPS[] = { ${SPEEDS.map((s) => s[1]).join(', ')} };

// the starting kit, expanded to NUM_VOICES * NP values
inline const float INIT_KIT[NV] = {
${Array.from({ length: NUM_VOICES }, (_, v) => '  ' + Array.from(kit.slice(v * NP, (v + 1) * NP), f).join(', ') + ',').join('\n')}
};

} // namespace fmdm
`;
writeFileSync(new URL('../plugin/engine/ParamsGen.h', import.meta.url), out);
console.log(`plugin/engine/ParamsGen.h: ${NP} voice params, ${MP} master params`);
